    private void btnAgregarEstudianteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarEstudianteActionPerformed

        controlador.agregarEstudiante(
            txtNombre.getText(),
            txtDireccion.getText(),
            txtTelefono.getText(),
            txtFecha.getText(),
            txtCodigo.getText(),
            txtGrado.getText()
        );

        javax.swing.JOptionPane.showMessageDialog(this, "¡Estudiante agregado correctamente!");

        txtNombre.setText("");
        txtDireccion.setText("");
        txtTelefono.setText("");
        txtFecha.setText("");
        txtCodigo.setText("");
        txtGrado.setText("");
        txtPromedio.setText("");
    }//GEN-LAST:event_btnAgregarEstudianteActionPerformed

    private void btnAgregarProfesorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarProfesorActionPerformed
        try {
            controlador.agregarProfesor(
                txtNombre.getText(),
                txtDireccion.getText(),
                txtTelefono.getText(),
                txtFecha.getText(),
                txtCedula.getText(),
                txtArea.getText(),
                Integer.parseInt(txtHoras.getText()),
                Double.parseDouble(txtValorHora.getText())
            );

            javax.swing.JOptionPane.showMessageDialog(this, "¡Profesor agregado correctamente!");

            txtNombre.setText("");
            txtDireccion.setText("");
            txtTelefono.setText("");
            txtFecha.setText("");
            txtCedula.setText("");
            txtArea.setText("");
            txtHoras.setText("");
            txtValorHora.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: En 'Horas/Mes' y 'Valor Hora' debes ingresar solo números.");
        }
    }//GEN-LAST:event_btnAgregarProfesorActionPerformed

